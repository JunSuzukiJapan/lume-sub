impl Language {
    /// このロケールの文言表
    pub fn strings(self) -> &'static UiStrings {
        use Language::*;
        match self {
            Arabic => &AR_STRINGS,
            Bengali => &BN_STRINGS,
            Dutch => &NL_STRINGS,
            English => &EN_STRINGS,
            French => &FR_STRINGS,
            German => &DE_STRINGS,
            Hebrew => &HE_STRINGS,
            Hindi => &HI_STRINGS,
            Indonesian => &ID_STRINGS,
            Italian => &IT_STRINGS,
            Japanese => &JA_STRINGS,
            Kannada => &KN_STRINGS,
            Korean => &KO_STRINGS,
            Malay => &MS_STRINGS,
            Mandarin => &ZH_STRINGS,
            Marathi => &MR_STRINGS,
            Polish => &PL_STRINGS,
            Portuguese => &PT_STRINGS,
            Spanish => &ES_STRINGS,
            Tagalog => &TL_STRINGS,
            Tamil => &TA_STRINGS,
            Telugu => &TE_STRINGS,
            Thai => &TH_STRINGS,
            Turkish => &TR_STRINGS,
            Vietnamese => &VI_STRINGS,
        }
    }

    /// `UI_LANG` 環境変数から読む。未設定なら None
    pub fn from_env() -> Option<Self> {
        let v = std::env::var("UI_LANG")
            .ok()
            .filter(|v| !v.is_empty())?;
        match v.parse() {
            Ok(l) => Some(l),
            Err(e) => {
                println!("⚠️ {e}（表示言語は英語にします）");
                Some(Language::English)
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_is_english() {
        assert_eq!(UiLocale::default(), Language::English);
    }

    #[test]
    fn ui_covers_all_subtitle_languages() {
        // 字幕対応言語＝UI表示言語（Language をそのまま使う）
        assert_eq!(UiLocale::all().len(), Language::all().len());
        for l in Language::all() {
            assert!(!l.strings().display_language.is_empty(), "{l:?}");
        }
    }

    #[test]
    fn all_locales_cover_every_string() {
        for l in UiLocale::all() {
            let t = l.strings();
            // 文言を足したらここにも足すこと
            for s in [
                t.display_language,
                t.status_stopped,
                t.status_running,
                t.status_paused,
                t.input_language,
                t.output_language,
                t.auto_detect,
                t.lang_read_failed,
                t.input_note,
                t.start,
                t.resume,
                t.pause,
                t.stop,
                t.quit,
                t.reset_position,
                t.follow_main_screen,
                t.control_title,
                t.connecting,
                t.play_prompt,
                t.drag_to_move,
                t.settings_button,
                t.settings_title,
                t.api_key,
                t.base_url,
                t.asr_model,
                t.translate_model,
                t.save,
                t.close,
                t.settings_restart_note,
                t.show_source,
                t.show_translation,
            ] {
                assert!(!s.is_empty(), "{l:?} has an empty string");
            }
            for tpl in [
                t.tpl_status_line,
                t.tpl_settings_line,
                t.tpl_listening,
                t.tpl_unsupported_audio,
            ] {
                assert_eq!(tpl.matches("{}").count(), 1, "{l:?} template: {tpl}");
            }
        }
    }

    #[test]
    fn templates_fill_in_locale_word_order() {
        let en = UiLocale::English.strings();
        assert_eq!(en.status_line("X"), "Status: X");
        assert_eq!(en.settings_line("Y"), "Settings: Y");
        assert_eq!(en.listening_text("P"), "🎧 Listening (P)...");
        assert_eq!(
            en.unsupported_audio_text("R"),
            "⚠️ Unsupported audio format: R"
        );
        let ja = UiLocale::Japanese.strings();
        assert_eq!(ja.status_line("X"), "状態: X");
        assert_eq!(ja.listening_text("P"), "🎧 P 聞き取り中...");
        // RTLロケールも論理順テンプレートのまま埋まる（表示整形は描画側）
        let ar = UiLocale::Arabic.strings();
        assert_eq!(ar.status_line("X"), "الحالة: X");
        assert_eq!(ar.listening_text("P"), "🎧 جارٍ الاستماع (P)...");
    }
}
